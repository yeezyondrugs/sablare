(function () {
  const lang = document.documentElement.lang === "ru" ? "ru" : "ro";
  const selectAll = (selector) => document.querySelectorAll(selector);

  window.ROOT = lang === "ru" ? "../" : "";

  window.t = function (key) {
    return I18N[lang][key] || I18N.ro[key] || key;
  };

  window.applyLang = function () {
    document.documentElement.lang = lang;

    selectAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });

    selectAll("[data-i18n-alt]").forEach((element) => {
      element.alt = t(element.dataset.i18nAlt);
    });

    selectAll("[data-i18n-aria]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAria));
    });

    const page = document.body.dataset.page;
    const description = document.querySelector("meta[name=description]");
    document.title = t("t_" + page);
    if (description) description.content = t("md_" + page);

    selectAll("[data-lang]").forEach((link) => {
      link.classList.toggle("on", link.dataset.lang === lang);
    });

    document.dispatchEvent(new Event("langchange"));
  };

  document.addEventListener("DOMContentLoaded", applyLang);
})();
